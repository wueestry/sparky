#!/usr/bin/env bash
# Turn upstream's start.sh into inputs for docker-compose.yml.
#
# upstream/start.sh is a rootful `docker run` wrapper (--network host,
# --gpus all, port probes with ss, PID matching against nvidia-smi). Instead of
# patching it, this asks it what it WOULD run (DRY_RUN=1 prints the docker
# command and exits) and reuses the parts that carry the recipe's decisions:
#
#   image, `tensorfold-native serve ...` arguments, every TENSORFOLD_* /
#   TF_FLASHNEXT_* engine variable, the two mounts (HF cache, kernel cache)
#
# Everything about HOW the container runs (network, GPU, ulimits, healthcheck,
# Traefik labels) lives in docker-compose.yml and is ours. So an upstream
# update that retunes the engine or adds a serve flag arrives by bumping the
# submodule; nothing here needs porting.
#
# Writes .generated/{compose.env,engine.env,dryrun.log}. Exit 1 when upstream's
# dry-run output no longer has the shape this expects: `make update` relies on
# that to catch breaking upstream changes before anything is deployed.
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")/.."

die() { echo "resolve: $*" >&2; exit 1; }
[[ -f upstream/start.sh ]] || die "upstream/ is empty: git submodule update --init models/qwen38/upstream"

GEN=.generated
mkdir -p "$GEN"

# 1. Upstream's own resolved settings. config.sh reads ./.env from here.
eval "$(
  set -euo pipefail
  # shellcheck source=/dev/null
  source upstream/scripts/config.sh >/dev/null
  printf 'IMAGE=%q HF_CACHE=%q\n' "$IMAGE" "$HF_CACHE"
)"

# 2. Ask start.sh what it would run.
log="$GEN/dryrun.log"
if ! out=$(DRY_RUN=1 ./scripts/run-upstream.sh upstream/start.sh 2>"$log"); then
  cat "$log" >&2
  die "upstream/start.sh DRY_RUN=1 failed"
fi
line=$(awk '/^\[dry-run\]$/ { getline; sub(/^ +/, ""); print; exit }' <<<"$out")
[[ -n "$line" ]] || die "no '[dry-run]' command in start.sh output: upstream changed its dry-run format"
# printf %q output from upstream's own script; eval turns it back into words.
eval "cmd=($line)"

# 3. Split it: options before the image, the serve command after it.
img=-1
for i in "${!cmd[@]}"; do [[ "${cmd[i]}" == "$IMAGE" ]] && { img=$i; break; }; done
(( img > 0 )) || die "image $IMAGE not found in the docker command: $line"
serve=("${cmd[@]:img+1}")
[[ "${serve[0]:-}" == tensorfold-native && "${serve[1]:-}" == serve ]] ||
  die "expected 'tensorfold-native serve ...' after the image, got: ${serve[*]:0:2}"

env_lines=(); hf_host=""; kernel_host=""
for (( i = 0; i < img; i++ )); do
  case "${cmd[i]}" in
    -e)
      kv=${cmd[i+1]}
      if [[ "$kv" == *=* ]]; then env_lines+=("$kv")
      elif [[ -n "${!kv:-}" ]]; then env_lines+=("$kv=${!kv}")   # name-only: TENSORFOLD_API_KEY
      fi ;;
    -v)
      m=${cmd[i+1]}
      case "$m" in
        *:/root/.cache/huggingface:ro) hf_host=${m%%:/root/.cache/huggingface:ro} ;;
        *:/cache)                      kernel_host=${m%%:/cache} ;;
      esac ;;
  esac
done
[[ -n "$hf_host" && -n "$kernel_host" ]] || die "could not find the HF cache / kernel cache mounts in: $line"

# 4. Values land in env files and a compose `command:`; refuse anything that
#    could be re-interpreted there rather than quote it and hope.
for tok in "${serve[@]}" "$hf_host" "$kernel_host" "$IMAGE"; do
  [[ "$tok" =~ ^[A-Za-z0-9_./:=@,+%-]+$ ]] || die "unexpected characters in '$tok'"
done
for kv in "${env_lines[@]}"; do
  [[ "$kv" =~ ^[A-Za-z_][A-Za-z0-9_]*=[^[:space:]\'\"\$\`\\]*$ ]] || die "unexpected characters in env value for ${kv%%=*}"
done

port=""
for (( i = 0; i < ${#serve[@]}; i++ )); do [[ "${serve[i]}" == --port ]] && port=${serve[i+1]}; done
[[ "$port" =~ ^[0-9]+$ ]] || die "no --port in the serve arguments"
name=""
for (( i = 0; i < ${#serve[@]}; i++ )); do [[ "${serve[i]}" == --name ]] && name=${serve[i+1]}; done
[[ -n "$name" ]] || die "no --name in the serve arguments"

model=${serve[2]}
model_host=$model
[[ "$model" == /root/.cache/huggingface/* ]] && model_host="$hf_host/${model#/root/.cache/huggingface/}"

mkdir -p "$kernel_host"
umask 077
printf '%s\n' "${env_lines[@]}" > "$GEN/engine.env"
{
  echo "# Generated by scripts/resolve.sh from upstream/start.sh. Do not edit."
  echo "TF_IMAGE=$IMAGE"
  echo "TF_HF_CACHE=$hf_host"
  echo "TF_KERNEL_CACHE=$kernel_host"
  echo "TF_PORT=$port"
  echo "TF_SERVED_NAME=$name"
  echo "TF_HOST_PORT=${HOST_PORT:-$port}"
  echo "TF_MODEL_DIR=$model_host"
  echo "TF_COMMAND='${serve[*]}'"
} > "$GEN/compose.env"

echo "resolve: ${serve[*]:0:3} … (${#serve[@]} words, ${#env_lines[@]} engine variables) → $GEN/"
